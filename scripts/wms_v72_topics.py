def get_topic_scenes(story_key: str) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    if story_key not in TOPIC_CONFIGS:
        raise KeyError(f"Unsupported v7.2 topic: {story_key!r}")
    return TOPIC_CONFIGS[story_key]()
